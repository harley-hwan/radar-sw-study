"""Build life_tu.cpp: the track-life view code exactly as it is in TrajectoryPlot.cpp (plus the helpers and
CTrackResult accessors it calls), wrapped with the Linux stubs. usage: python extract.py <TargetSimUI dir> <out cpp>"""
import re
import sys

ui, out = sys.argv[1], sys.argv[2]
plot = open(f'{ui}/TrajectoryPlot.cpp', encoding='utf-8').read().split('\n')
res = open(f'{ui}/PlotResult.cpp', encoding='utf-8').read().split('\n')


def block(lines, start_pat):
    """Lines from the first line matching start_pat through the next line that is exactly '}'."""
    i = next(k for k, l in enumerate(lines) if re.match(start_pat, l))
    j = next(k for k in range(i, len(lines)) if lines[k] == '}')
    return lines[i:j + 1]


# 상수 (#define) 와 범례 typedef: PLOT_MARGIN_LEFT 부터 ST_LifeLegend 까지
i = next(k for k, l in enumerate(plot) if l.startswith('#define PLOT_MARGIN_LEFT'))
j = next(k for k, l in enumerate(plot) if l.startswith('} ST_LifeLegend;'))
consts = plot[i:j + 1]

helpers = []
for name in ('f_Plot_Color', 'f_Plot_Round', 'f_Plot_NiceStepFrom', 'f_Plot_NiceStepMeter', 'f_Plot_DecimalFor', 'f_Plot_Number',
             'f_Plot_Text', 'f_Plot_ObjectName', 'f_Plot_TrackStateColor'):
    helpers += block(plot, rf'static \w[\w:]* \*?{name}\(') + ['']

i = next(k for k, l in enumerate(plot) if l == '// CTrackLifeView')
life = plot[i:]

acc = []
for name in ('f_GetScanNum', 'f_FindScan', 'f_GetTrackNum', 'f_GetTrack', 'f_GetScan'):
    acc += block(res, rf'^[\w ]+\*?\s*CTrackResult::{name}\(') + ['']

head = '''// generated by extract.py from TrajectoryPlot.cpp / PlotResult.cpp (do not edit)
#include "afx_stub.h"
#define private public
#define protected public
#include "UiCommon.h"
#include "TrajectoryPlot.h"
'''
open(out, 'w', encoding='utf-8').write(head + '\n'.join(consts + [''] + helpers + life + [''] + acc) + '\n')
print('wrote', out, len(consts), len(helpers), len(life), len(acc))
